const STRINGS: Record<Lang, typeof EN> = { en: EN, fa: FA, zh: ZH, ru: RU };

export function getCurrentLang(): Lang {
  return codeForLabel(useSettingsStore.getState().language);
}

/** Non-hook translator for use outside React (services/stores, e.g. vpnStore
 *  toasts). Resolves against the current language, falls back to EN then key. */
export function tr(key: TKey | (string & {})): string {
  const lang = getCurrentLang();
  return (STRINGS[lang] as any)[key] ?? (EN as any)[key] ?? key;
}

export function useT() {
  const language = useSettingsStore((s) => s.language);
  const lang: Lang = codeForLabel(language);
  const isRTL = lang === 'fa';
  const dict  = STRINGS[lang];

  // Accepts known keys (with autocomplete) plus dynamic keys built at runtime
  // (e.g. tagLabelKey/greeting). Unknown keys fall back to the key string.
  function t(key: TKey | (string & {})): string {
    return (dict as any)[key] ?? (EN as any)[key] ?? key;
  }

  return { t, isRTL, lang };
}

