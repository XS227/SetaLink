<p>اینستاگرام (و واتساپ) از پروتکلی به نام <strong>QUIC</strong> استفاده می‌کنند — نسخه‌ای از ترافیک اینترنت که روی UDP کار می‌کند، نه TCP معمولی. خیلی از فیلترشکن‌ها فقط ترافیک TCP را درست از تونل عبور می‌دهند؛ نتیجه این می‌شود که سایت‌های عادی باز می‌شوند ولی اینستاگرام روی «در حال بارگذاری» گیر می‌کند، عکس‌ها می‌آیند ولی ویدیوها نه، یا استوری‌ها اصلاً لود نمی‌شوند.</p>
