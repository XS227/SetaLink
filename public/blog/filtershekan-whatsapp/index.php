<h2>چرا پیام می‌رود ولی تماس واتساپ وصل نمی‌شود؟</h2>
<p>پیام‌های واتساپ از مسیر معمولی (TCP) رد می‌شوند، ولی <strong>تماس صوتی و تصویری روی UDP</strong> کار می‌کند. خیلی از فیلترشکن‌ها UDP را یا اصلاً عبور نمی‌دهند یا ناقص عبور می‌دهند — نتیجه: پیام‌ها می‌روند، ولی تماس یا وصل نمی‌شود یا بعد از چند ثانیه قطع می‌شود. ری‌لینک تونل تمام‌دستگاه (full-device) دارد و ترافیک UDP تماس‌ها هم از همان تونل رد می‌شود؛ برای تماس واتساپ چیز جداگانه‌ای لازم نیست روشن کنید.</p>

<h2>قدم اول (مهم‌ترین): واتساپ را بعد از اتصال کامل ببندید</h2>
<p>واتساپ هم مثل اینستاگرام از پروتکل <strong>QUIC</strong> استفاده می‌کند و اتصال قبلی‌اش را نگه می‌دارد. اگر فیلترشکن را وصل کرده‌اید ولی واتساپ هنوز «در انتظار پیام» مانده یا عکس پروفایل‌ها لود نمی‌شود:</p>
<ul>
  <li>واتساپ را <strong>کاملاً ببندید</strong> (force-quit)</li>
  <li>دوباره باز کنید — چند ثانیه صبر کنید تا همگام شود</li>
</ul>
<p>بعد از هر تعویض سرور یا به‌روزرسانی برنامه هم همین کار را بکنید. این ساده‌ترین و مؤثرترین راه‌حل است.</p>

<h2>تلگرام چطور؟</h2>
